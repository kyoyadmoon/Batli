function buildTaiAudioRelatedWords(character: string, words: readonly VocabRelatedWord[]): VocabRelatedWord[] {
  const deduped = new Set<string>();
  const result: VocabRelatedWord[] = [];

  for (const item of words) {
    if (!hasTaiAudio(item.word) || deduped.has(item.word)) continue;
    deduped.add(item.word);
    result.push(item);
  }

  for (const item of AUDIO_SUPPLEMENTS_BY_CHARACTER[character] ?? []) {
    if (!hasTaiAudio(item.word) || deduped.has(item.word)) continue;
    deduped.add(item.word);
    result.push(item);
    if (result.length >= 6) {
      break;
    }
  }

  return result.slice(0, 6);
}

function getBaseRelatedWordsForVocab(vocab: VocabCharacter): readonly VocabRelatedWord[] {
  if (vocab.relatedWords && vocab.relatedWords.length >= 2) {
    return vocab.relatedWords.slice(0, 6);
  }

  const fromMap = RELATED_WORDS_BY_CHARACTER[vocab.character];
  if (fromMap) {
    return fromMap.slice(0, 6);
  }

  if (vocab.contextWord) {
    return [
      rw(
        CONTEXT_WORD_EMOJI_BY_WORD[vocab.contextWord] ?? '📘',
        vocab.contextWord,
        vocab.contextPronunciation ?? vocab.contextWord,
      ),
    ];
  }

  return [];
}

export function getRelatedWordsForVocab(vocab: VocabCharacter): readonly VocabRelatedWord[] {
  return getBaseRelatedWordsForVocab(vocab);
}

export function getTaiAudioRelatedWordsForVocab(vocab: VocabCharacter): readonly VocabRelatedWord[] {
  const baseWords = getBaseRelatedWordsForVocab(vocab);
  if (baseWords.length > 0) {
    return buildTaiAudioRelatedWords(vocab.character, baseWords);
  }

  if (hasTaiAudio(vocab.character)) {
    return [rw('🔤', vocab.character, vocab.pronunciation)];
  }

  return [];
}
